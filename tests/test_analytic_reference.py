# Case A -- 1D, Dirichlet at both ends.  L=1, m=0.5, n=1..6.  Formula (3.2).
# ---------------------------------------------------------------------------
CASE_A = [
    # n, lambda, omega^2, omega
    (1, "9.86960440109", "10.1196044011", "3.18113256578"),
    (2, "39.4784176044", "39.7284176044", "6.30304827876"),
    (3, "88.8264396098", "89.0764396098", "9.43803155376"),
    (4, "157.913670417", "158.163670417", "12.5763138645"),
    (5, "246.740110027", "246.990110027", "15.7159190004"),
    (6, "355.305758439", "355.555758439", "18.8561862114"),
]


def test_case_A_dirichlet_1d():
    spec = spectrum_1d(Dirichlet(), Dirichlet(), 1.0, 6, m=0.5)
    for i, (n, lam, w2, w) in enumerate(CASE_A):
        assert_sig_figs(spec.lam[i], lam, label=f"A n={n} lambda")
        assert_sig_figs(spec.omega2[i], w2, label=f"A n={n} omega^2")
        assert_sig_figs(spec.omega[i].real, w, label=f"A n={n} omega")
        assert spec.omega[i].imag == 0.0
    # (3.2): lambda_n = (n pi/L)^2, k_n = n pi/L, no zero mode
    assert_sig_figs(spec.lam[0], PI**2, label="A lambda_1 = pi^2")


