"""The spec section 5 reference table, asserted to 12 significant figures.

Every number in the tables below is copied verbatim from
``docs/bc-conventions.md`` section 5.  They were generated by the theorist with
mpmath at 50-digit precision from the closed forms of section 3; the assertion
here is that :mod:`worldvolume.analytic` reproduces them, and that the values in
turn satisfy the identities the spec gives as cross-checks (the ``tan`` form of
the Robin condition, the normalisation integral, the multiplicity formula).

``assert_sig_figs`` compares to within half a unit in the 12th significant
digit, which is the strict reading of "quoted to 12 significant figures".
"""

