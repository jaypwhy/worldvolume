def _r2(q: int) -> int:
    """Number of representations of q as a sum of two squares of integers."""
    return 4 * sum(1 for d in range(1, q + 1) if q % d == 0 and d % 4 == 1) - 4 * sum(
        1 for d in range(1, q + 1) if q % d == 0 and d % 4 == 3
    )


def test_multiplicity_formula_3_22():
    # spec 3.6.2: mult_DD(q) = (r_2(q) - 4 [sqrt(q) in Z]) / 4
    expected = {2: 1, 5: 2, 8: 1, 10: 2, 13: 2, 17: 2, 18: 1, 20: 2, 25: 2, 26: 2, 29: 2, 32: 1}
    for q, mult in expected.items():
        axis = 4 if int(math.isqrt(q)) ** 2 == q else 0
        assert (_r2(q) - axis) // 4 == mult
    # and the multiplicities actually realised by the enumerated spectrum
    spec = spectrum_2d(Dirichlet(), Dirichlet(), 1.0, Dirichlet(), Dirichlet(), 1.0, 40)
    for q, mult in expected.items():
        n = np.sum(np.isclose(spec.lam, PI**2 * q, rtol=1e-9))
        assert n == mult, f"q={q}: found {n} levels, formula says {mult}"
