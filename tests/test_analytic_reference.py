def test_case_D_robin_equal_couplings():
    k = robin_wavenumbers(2.0, 2.0, 1.0, 7)
    for i, (n, kk, lam) in enumerate(CASE_D):
        assert_sig_figs(k[i], kk, label=f"D n={n} k")
        assert_sig_figs(k[i] ** 2, lam, label=f"D n={n} lambda")
    # cross-check given in the spec: tan k = 4k/(k^2-4) for kappa = 2, L = 1
    for kk in k:
        assert math.tan(kk) == pytest.approx(4 * kk / (kk**2 - 4), rel=1e-12)
    # the spectrum is the roots of (3.12) with no zero mode (3.18 fails)
    assert k[0] > 0.0
    assert np.all(np.diff(k) > 0.0)
    # m = 0, so omega = k
    spec = spectrum_1d(Robin(2.0), Robin(2.0), 1.0, 7, m=0.0)
    assert np.allclose(spec.omega.real, k, rtol=1e-13)
    assert np.all(spec.omega.imag == 0.0)


def test_case_D_normalisation_integrals():
    # spec 3.5.2: I(k_1) = 1.851033886878379, I(k_2) = 0.742962685095034,
    # I(k_3) = 0.585216171650906 -- not constant and not L/2
    k = robin_wavenumbers(2.0, 2.0, 1.0, 3)
    for kk, printed in zip(
        k, ("1.851033886878379", "0.742962685095034", "0.585216171650906")
    ):
        assert_sig_figs(robin_normalisation(kk, 2.0, 1.0), printed, label="I(k)")
    # and it agrees with direct quadrature
    from scipy.integrate import quad

    for kk in k:
        c = 2.0 / kk
        numeric = quad(lambda x: (math.cos(kk * x) + c * math.sin(kk * x)) ** 2, 0.0, 1.0)[0]
        assert robin_normalisation(kk, 2.0, 1.0) == pytest.approx(numeric, rel=1e-12)


